#!/usr/bin/env python3
"""Generates crates/victory-formats/src/texture_xor.rs from AMD's gfx10SwizzlePattern.h (addrlib, MIT).

Usage: gen_xor_tables.py <gfx10SwizzlePattern.h> > crates/victory-formats/src/texture_xor.rs

The header is part of addrlib (Mesa: src/amd/addrlib/src/gfx10/, or AMD's PAL: imported/addrlib). Only the RB+ tables
(RDNA2) of the modes the texture layouts use are kept, and the nibble rows they refer to, renumbered.
"""
import re
import sys

# Rust name -> table in the header.
TABLES = [
    ("SW_256B_S", "GFX10_SW_256_S_RBPLUS_PATINFO"),
    ("SW_256B_D", "GFX10_SW_256_D_RBPLUS_PATINFO"),
    ("SW_4KB_S", "GFX10_SW_4K_S_RBPLUS_PATINFO"),
    ("SW_4KB_D", "GFX10_SW_4K_D_RBPLUS_PATINFO"),
    ("SW_64KB_S", "GFX10_SW_64K_S_RBPLUS_PATINFO"),
    ("SW_64KB_D", "GFX10_SW_64K_D_RBPLUS_PATINFO"),
    ("SW_4KB_S3", "GFX10_SW_4K_S3_RBPLUS_PATINFO"),
    ("SW_64KB_S3", "GFX10_SW_64K_S3_RBPLUS_PATINFO"),
    ("SW_64KB_S_T", "GFX10_SW_64K_S_T_RBPLUS_PATINFO"),
    ("SW_64KB_D_T", "GFX10_SW_64K_D_T_RBPLUS_PATINFO"),
    ("SW_64KB_S3_T", "GFX10_SW_64K_S3_T_RBPLUS_PATINFO"),
    ("SW_4KB_S_X", "GFX10_SW_4K_S_X_RBPLUS_PATINFO"),
    ("SW_4KB_D_X", "GFX10_SW_4K_D_X_RBPLUS_PATINFO"),
    ("SW_4KB_S3_X", "GFX10_SW_4K_S3_X_RBPLUS_PATINFO"),
    ("SW_64KB_S_X", "GFX10_SW_64K_S_X_RBPLUS_PATINFO"),
    ("SW_64KB_D_X", "GFX10_SW_64K_D_X_RBPLUS_PATINFO"),
    ("SW_64KB_S3_X", "GFX10_SW_64K_S3_X_RBPLUS_PATINFO"),
    ("SW_64KB_D3_X", "GFX10_SW_64K_D3_X_RBPLUS_PATINFO"),
    ("SW_64KB_Z_X", "GFX10_SW_64K_Z_X_1xaa_RBPLUS_PATINFO"),
    ("SW_64KB_R_X", "GFX10_SW_64K_R_X_1xaa_RBPLUS_PATINFO"),
]
NIBBLES = [("NIBBLE01", 8), ("NIBBLE2", 4), ("NIBBLE3", 4), ("NIBBLE4", 4)]


def body(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\[[^\]]*\](?:\[[^\]]*\])?\s*=\s*\{(.*?)\n\};", text, re.S)
    if not m:
        sys.exit(f"missing {name}")
    return m.group(1)


def patinfo(text, name):
    rows = []
    for line in body(text, name).splitlines():
        m = re.match(r"\s*\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*\}", line)
        if m:
            rows.append([int(g) for g in m.groups()][1:])
    return rows


def bit(expr):
    """An address bit: the XOR of coordinate bits, as masks of x, y, z (samples are 1: s is 0)."""
    mask = {"X": 0, "Y": 0, "Z": 0}
    expr = expr.strip()
    if expr != "0":
        for term in expr.split("^"):
            term = term.strip()
            c, n = term[0], int(term[1:])
            if c == "S":
                continue
            mask[c] |= 1 << n
    return [mask["X"], mask["Y"], mask["Z"]]


def nibbles(text, name, width):
    rows = []
    for line in body(text, "GFX10_SW_PATTERN_" + name).splitlines():
        m = re.match(r"\s*\{(.*?)\},?\s*//\s*(\d+)", line)
        if m:
            cells = [c for c in m.group(1).split(",") if c.strip()]
            assert len(cells) == width, line
            assert int(m.group(2)) == len(rows)
            rows.append([bit(c) for c in cells])
    return rows


def main():
    text = open(sys.argv[1]).read()
    infos = {rust: patinfo(text, header) for rust, header in TABLES}
    pool = {n: nibbles(text, n, w) for n, w in NIBBLES}
    # Renumber the rows the tables refer to.
    used = [{} for _ in NIBBLES]
    for rows in infos.values():
        assert len(rows) == 75, len(rows)
        for r in rows:
            for k in range(4):
                used[k].setdefault(r[k], len(used[k]))
    out = []
    w = out.append
    w("//! Swizzle equations of the console GPU's XOR texture modes, generated by")
    w("//! `tools/swizzle/gen_xor_tables.py` from addrlib's `gfx10SwizzlePattern.h` (the RB+ tables, as on RDNA2).")
    w("//! addrlib is MIT licensed and carries the notice reproduced in `texture.rs`. Do not edit by hand.")
    w("")
    w("/// One address bit: the XOR of the coordinate bits `x`, `y` and `z` select (bit `n` of a mask is bit `n`")
    w("/// of the coordinate).")
    w("pub type Bit = [u16; 3];")
    w("")
    for (name, width), u in zip(NIBBLES, used):
        w(f"/// {name} rows: address bits 0-7, 8-11, 12-15 or 16-19 of the patterns that use them.")
        w(f"pub static {name}: [[Bit; {width}]; {len(u)}] = [")
        for old in u:
            row = pool[name][old]
            w("    [" + ", ".join("[%#x, %#x, %#x]" % tuple(b) for b in row) + "],")
        w("];")
        w("")
    w("// Pattern rows `[nibble 0-7, 8-11, 12-15, 16-19]` per (pipes, packers) configuration and element size:")
    w("// row `5 * configuration + log2(element bytes)`, 15 configurations (`PipeConfig::row`).")
    for rust, rows in infos.items():
        if not rust.endswith(("_X", "_T")):
            w("#[cfg(test)] // the modes without XOR have their own tables: used to check these against them")
        w(f"pub static {rust}: [[u16; 4]; 75] = [")
        for r in rows:
            w("    [" + ", ".join(str(used[k][r[k]]) for k in range(4)) + "],")
        w("];")
        w("")
    print("\n".join(out))


main()
